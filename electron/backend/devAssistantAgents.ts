/**
 * 开发助手子代理注册表（多智能体编排的服务端侧定义）。
 *
 * ── 为什么要在这里定义 ─────────────────────────────────────────
 * opencode 的子代理（task 工具里 subagent_type 指向的那个 agent）必须先由服务端
 * 配置声明，`buildSdkConfig` 再通过 OPENCODE_CONFIG_CONTENT 注入。渲染进程无法
 * 在运行时注册 agent，所以定义落在 electron 侧。
 *
 * ── 与 src/hooks/opencode/opencodeInstructions.ts 的分工 ────────
 * 本文件**只承载「子代理角色包装」**：子代理是独立会话，看不到主会话历史，也拿不到
 * 主智能体的完整系统指令，因此这里只声明它「是谁、必须先读哪些文件、边界在哪」。
 * 代码头字段模板、@引擎 取值、指标表头、稽核规则 5 列表这些机器解析契约**不在这里
 * 复制**（否则与 src 侧提示词形成两份会漂移的事实源）。主智能体分派任务时，必须在
 * 任务描述里原样带上这些规范摘要 —— 该要求写在 S2/S3 提示词的「多智能体并行编排」章节里。
 *
 * ⚠ 改动前必读：
 * - 本文件的 agent 名称必须与 src/hooks/opencode/devAssistantAgents.ts 的常量逐字一致，
 *   由 devAssistantAgents.test.ts 断言（渲染进程侧提示词要用同一个名字去 task 分派）。
 * - 本文件保持**零依赖**：vitest 会直接 import 它做契约断言，引入 electron 模块会挂。
 */

/** 子代理定义（对齐 SDK 的 AgentConfig，只取本场景用到的字段） */
export interface DevAssistantSubagent {
  /** 给主智能体看的用途描述，task 工具据此选择子代理 */
  description: string;
  /** 固定为 subagent：只允许被 task 工具派生，不出现在主智能体切换列表里 */
  mode: 'subagent';
  /** 子代理自身的系统指令（角色包装，不含机器解析契约） */
  prompt: string;
}

