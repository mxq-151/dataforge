/**
 * 开发助手子代理注册表（多智能体编排的服务端侧定义，名称与定义的单一事实源）。
 *
 * ── 为什么要在这里定义 ─────────────────────────────────────────
 * opencode 的子代理（task 工具里 subagent_type 指向的那个 agent）必须先由服务端
 * 配置声明，`buildSdkConfig` 再通过 OPENCODE_CONFIG_CONTENT 注入。渲染进程无法
 * 在运行时注册 agent，所以定义落在 electron 侧。
 *
 * ── 与 src 侧的关系 ───────────────────────────────────────────
 * 本文件是子代理**名称与定义的唯一事实源**：electron 的 tsconfig rootDir 锁在
 * electron/、不能 import src；反向没有限制——渲染侧由 vite 构建、无 rootDir，
 * 直接从本文件 re-export 名称常量（见 src/hooks/opencode/devAssistantAgents.ts），
 * 两侧不再各写一份，一致性由编译期保证。
 *
 * 提示词正文在 src/hooks/opencode/prompts/ 下按任务类型拆分。本文件**只承载
 * 「子代理角色包装」**：子代理是独立会话，看不到主会话历史，也拿不到主智能体的
 * 完整系统指令，因此这里只声明它「是谁、必须先读哪些文件、边界在哪」。代码头字段
 * 模板、@引擎 取值、指标表头、稽核规则 5 列表这些机器解析契约**不在这里复制**
 * （否则与 src 侧提示词形成两份会漂移的事实源）。主智能体分派任务时，必须在
 * 任务描述里原样带上这些规范摘要 —— 该要求写在各任务提示词的编排章节里。
 *
 * ⚠ 本文件保持**零依赖**：渲染进程与 vitest 都会直接 import 它（前者经
 * re-export 进 vite 构建，后者做契约断言），引入 electron 模块会挂。
 */

/** 子代理定义（对齐 SDK 的 AgentConfig，只取本场景用到的字段） */
export interface DevAssistantSubagent {
  /** 给主智能体看的用途描述，task 工具据此选择子代理 */
  description: string;
  /** 固定为 subagent：只允许被 task 工具派生，不出现在主智能体切换列表里 */
  mode: 'subagent';
  /** 子代理自身的系统指令（角色包装，不含机器解析契约） */
  prompt: string;
}

