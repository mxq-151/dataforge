/**
 * 数仓开发 —— 把「数仓设计」「设计校验」「代码开发」「代码校验」串成一条带门禁的闭环，
 * 由主智能体充当编排者，按交付单元派生四类子代理。
 *
 * ── 为什么不再是「一张表一个子代理」 ─────────────────────────
 * 按表硬拆会切断同一业务域内上下游表的联系：字段口径、指标编码、依赖指向各自由不同
 * 子代理独立决定，错误顺着 DAG 逐层放大，往往到代码验收阶段才暴露，返工面积不可控。
 * 现在把派发单位对齐设计文档定义的交付单元：
 * - 设计按**设计单元**（同业务域 1~3 张表，可跨分层）派发，单元内口径与依赖一次对齐
 * - 开发按**处理任务**派发，一个处理任务可覆盖多张表，与其调度边界一致
 *
 * ── 为什么设计校验只做一次、且必须等全部层次设计完成 ─────────
 * 数仓分层是一个整体：跨层依赖方向、命名口径、指标归属只有放在全量设计里才判断得了。
 * 边设计边校验时校验方看不到后续分层，只能确认「本批内部自洽」，会把局部自洽、全局冲突
 * 的设计放行，分层就失去全局观。因此设计阶段一次性完成所有层次并统一落盘，再交
 * design-verifier 做一次全量校验；通过后才进入代码开发。
 * 设计校验与代码校验各设两轮复验上界，到上界仍不通过就停下来报告用户，不允许靠
 * 「先放行、后面再说」把问题推给下游。
 *
 * ── 与 S2/S3 自带编排章节的冲突 ──────────────────────────────
 * MULTI_AGENT_ORCHESTRATION_S2/S3 按「≥3 张 / ≥2 张表」设了阈值、按表粒度分派与
 * "不足时自己做"的退路。本任务类型要把派发变成确定性动作，故在编排纪律里显式声明这些
 * 条款不适用；两个常量本身不改动，它们仍服务于单独选中设计/开发的场景。
 */
