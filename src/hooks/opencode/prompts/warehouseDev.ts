/**
 * 数仓开发任务提示词（设计 → 设计校验 → 代码开发 → 代码校验的闭环编排）。
 *
 * 编排模式：每个阶段派生**一个**子代理统一完成该阶段全部工作——阶段一一个
 * data-architect 完成全部设计，阶段二一个 design-verifier 整体校验，阶段三一个
 * data-dev 完成全部编码，阶段四一个 data-verifier 统一验收。
 *
 * ── 为什么不拆分派发 ─────────────────────────────────────────
 * 无论按表、按设计单元还是按处理任务拆，都会把同一份产物的不同部分交给互相看不到
 * 对方的子代理：字段口径、指标编码、依赖指向各自决定，错误顺着 DAG 逐层放大，
 * 到代码验收才暴露，返工面积不可控。统一完成天然保住全局观：一个会话看着全部表
 * 做设计，跨层依赖与命名口径天然一致；校验也整体做一次，才能发现
 * 「局部自洽、全局冲突」的设计。
 *
 * ── 主智能体是纯编排者 ───────────────────────────────────────
 * 设计与编码产物由子代理直接落盘（data-architect 写设计文档与 DDL，data-dev 写
 * 程序文件），主智能体不写表级产物、不汇总片段，只做四件事：
 * 分派 → 转达规范 → 打回修复 → 校验收口。
 */

